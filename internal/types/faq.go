// normalizeQuestionStrings normalizes the question list
// Includes full-width to half-width conversion, trailing punctuation removal, whitespace collapsing, and deduplication
func normalizeQuestionStrings(values []string) []string {
	if len(values) == 0 {
		return nil
	}
	dedup := make([]string, 0, len(values))
	seen := make(map[string]struct{}, len(values))
	for _, v := range values {
		normalized := NormalizeQuestion(v)
		if normalized == "" {
			continue
		}
		if _, exists := seen[normalized]; exists {
			continue
		}
		seen[normalized] = struct{}{}
		dedup = append(dedup, normalized)
	}
	if len(dedup) == 0 {
		return nil
	}
	return dedup
}

// multiSpaceRegex matches multiple consecutive whitespace characters
var multiSpaceRegex = regexp.MustCompile(`\s+`)

// urlRegex matches URLs
var urlRegex = regexp.MustCompile(`https?://[^\s]+`)

// URLNormMode defines the URL normalization mode
type URLNormMode int

const (
	// URLRemove removes the URL entirely
	URLRemove URLNormMode = iota
	// URLPlaceholder replaces it with the placeholder <URL>
	URLPlaceholder
	// URLKeepDomain keeps only the domain
	URLKeepDomain
	// URLKeepDomainAndPath keeps the domain and path
	URLKeepDomainAndPath
)

// NormalizeQuestion normalizes the question text to improve vector matching hit rate
// Processing order reference: query = convert_st(trim_url(query.lower().strip().strip("？。，；、：""！?.,;!:'\"")), 1)
// 1. Trim leading and trailing whitespace
// 2. Remove URLs
// 3. Convert to lowercase
// 4. Strip leading and trailing punctuation
// 5. Convert Traditional Chinese to Simplified
// 6. Convert full-width symbols to half-width
// 7. Smart space handling (remove spaces between Chinese characters, keep between English/numbers)
func NormalizeQuestion(q string) string {
	q = strings.TrimSpace(q)
	if q == "" {
		return ""
	}

	// 1. Remove URLs
	q = trimURL(q)

	// 2. Convert to lowercase (effective for English)
	q = strings.ToLower(q)

	// 3. Strip leading and trailing punctuation
	q = strings.Trim(q, `？。，；、：""！?.,;!:'""`)

	// 4. Convert Traditional Chinese to Simplified
	q = toSimplified(q)

	// 5. Convert full-width characters to half-width
	q = toHalfWidth(q)

	// 6. Smart space handling: remove spaces between Chinese characters, keep between English/numbers
	q = normalizeSpaces(q)

	return strings.TrimSpace(q)
}

// normalizeSpaces handles spaces intelligently
// Rules:
// - Remove extra spaces in Chinese context
// - Keep necessary spaces between English/numbers
// Examples:
// - "怎么 绑定 手机" → "怎么绑定手机"
// - "iphone 15 怎么 激活" → "iphone 15怎么激活"
func normalizeSpaces(s string) string {
	// First merge multiple consecutive spaces into a single space
	s = multiSpaceRegex.ReplaceAllString(s, " ")

	runes := []rune(s)
	if len(runes) == 0 {
		return ""
	}

	var builder strings.Builder
	builder.Grow(len(s))

	for i := 0; i < len(runes); i++ {
		r := runes[i]

		// If it's not a space, write it directly
		if r != ' ' {
			builder.WriteRune(r)
			continue
		}

		// Handle spaces: check surrounding characters to decide whether to keep them
		// Get the previous non-space character
		var prevRune rune
		if i > 0 {
			prevRune = runes[i-1]
		}

		// Get the next non-space character
		var nextRune rune
		for j := i + 1; j < len(runes); j++ {
			if runes[j] != ' ' {
				nextRune = runes[j]
				break
			}
		}

		// Only keep the space when both surrounding characters are English letters or digits
		// Otherwise (including Chinese) remove the space
		if isASCIIAlphaNum(prevRune) && isASCIIAlphaNum(nextRune) {
			builder.WriteRune(' ')
		}
		// Otherwise skip the space
	}

	return builder.String()
}

// isASCIIAlphaNum checks whether a character is an ASCII letter or digit
func isASCIIAlphaNum(r rune) bool {
	return (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9')
}

// trimURL removes URLs from the string (using the default URLRemove pattern)
func trimURL(s string) string {
	return NormalizeURL(s, URLRemove)
}

// NormalizeURL processes URLs in the text according to the specified pattern
func NormalizeURL(text string, mode URLNormMode) string {
	return urlRegex.ReplaceAllStringFunc(text, func(raw string) string {
		switch mode {
		case URLRemove:
			return ""
		case URLPlaceholder:
			return "<URL>"
		case URLKeepDomain:
			domain, _ := parseURL(raw)
			if domain != "" {
				return domain
			}
			return "<URL>"
		case URLKeepDomainAndPath:
			domain, path := parseURL(raw)
			if domain != "" {
				return domain + path
			}
			return "<URL>"
		default:
			return "<URL>"
		}
	})
}

// parseURL parses a URL and returns the domain and path
func parseURL(raw string) (domain, path string) {
	// Remove the protocol prefix
	u := raw
	if strings.HasPrefix(u, "https://") {
		u = u[8:]
	} else if strings.HasPrefix(u, "http://") {
		u = u[7:]
	}

	// Separate domain and path
	slashIdx := strings.Index(u, "/")
	if slashIdx == -1 {
		// No path, the whole thing is the domain (may include query parameters)
		queryIdx := strings.Index(u, "?")
		if queryIdx != -1 {
			domain = u[:queryIdx]
		} else {
			domain = u
		}
		return domain, ""
	}

	domain = u[:slashIdx]
	path = u[slashIdx:]

	// Remove query parameters and fragment
	if queryIdx := strings.Index(path, "?"); queryIdx != -1 {
		path = path[:queryIdx]
	}
	if fragIdx := strings.Index(path, "#"); fragIdx != -1 {
		path = path[:fragIdx]
	}

	return domain, path
}

// toSimplified converts Traditional Chinese to Simplified Chinese
func toSimplified(s string) string {
	return textconv.ToSimplified(s)
}

// toHalfWidth converts full-width characters to half-width characters
// Mainly handles: full-width spaces, full-width ASCII characters (including punctuation)
func toHalfWidth(s string) string {
	var builder strings.Builder
	builder.Grow(len(s))

	for _, r := range s {
		switch {
		// Full-width space -> half-width space
		case r == '\u3000':
			builder.WriteRune(' ')
		// Full-width ASCII characters (! to ~, range 0xFF01-0xFF5E) -> half-width (0x0021-0x007E)
		case r >= 0xFF01 && r <= 0xFF5E:
			builder.WriteRune(r - 0xFF01 + 0x21)
		// Other characters remain unchanged
		default:
			builder.WriteRune(r)
		}
	}

	return builder.String()
}

